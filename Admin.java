    private void jButton17ActionPerformed(java.awt.event.ActionEvent evt) {                                          
        
java.sql.Date currentDate = new java.sql.Date(System.currentTimeMillis());
    java.sql.Date returnDate = new java.sql.Date(currentDate.getTime() + 14L * 24 * 60 * 60 * 1000);
    String countSql = "SELECT COUNT(*) FROM issuedbook WHERE studentid = ? AND issueddate = ?";
    String insertSql = "INSERT INTO issuedbook (studentid, bookid, issueddate, returneddate, penalty)" +
                       "VALUES (?, ?, ?, ?, 0)";
    String updateBookSql = "UPDATE book SET available = available - 1 WHERE bookid = ? AND available > 0";
    
    try {
        
        con.setAutoCommit(false);
        try (PreparedStatement countStmt = con.prepareStatement(countSql)) {
            countStmt.setString(1, stdid.getText());  
            countStmt.setDate(2, currentDate);      
            ResultSet resultSet = countStmt.executeQuery();
            resultSet.next();
            int booksIssuedToday = resultSet.getInt(1);
            if (booksIssuedToday >= 3) {
                JOptionPane.showMessageDialog(null, "You cannot issue more than 3 books today.", "Limit Reached", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        try (PreparedStatement insertStmt = con.prepareStatement(insertSql)) {
            insertStmt.setString(1, stdid.getText());   
            insertStmt.setString(2, bookid.getText());  
            insertStmt.setDate(3, currentDate);         
            insertStmt.setDate(4, returnDate);     
            int rowsInserted = insertStmt.executeUpdate();
            if (rowsInserted > 0) {
                try (PreparedStatement updateStmt = con.prepareStatement(updateBookSql)) {
                    updateStmt.setString(1, bookid.getText());  
                    int rowsUpdated = updateStmt.executeUpdate();
                    if (rowsUpdated > 0) {
                        JOptionPane.showMessageDialog(null, "Book issued successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
                    } else {
                        JOptionPane.showMessageDialog(null, "No copies available for this book.", "Error", JOptionPane.ERROR_MESSAGE);
                    }
                }
            } else {
                JOptionPane.showMessageDialog(null, "Failed to issue book. Try again.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
        con.commit();
    } catch (SQLException e) {
        try {
            con.rollback();
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
        e.printStackTrace();
        JOptionPane.showMessageDialog(null, "Database error occurred during book issuance!", "Error", JOptionPane.ERROR_MESSAGE);
    } finally {
        try {
            con.setAutoCommit(true);
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
    }                                         

