    private void jButton15ActionPerformed(java.awt.event.ActionEvent evt) {                                          
        // TODO add your handling code here:
                int selectedRow = table.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "Please select a book to return.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

     
        String bookID = table.getValueAt(selectedRow, 0).toString(); 
        String studentID = stid.getText(); 

        if (studentID.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Student ID is required.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            
            con.setAutoCommit(false);
            String updateBookSql = "UPDATE book SET available = available + 1 WHERE bookid = ?";
            PreparedStatement updateBookStmt = con.prepareStatement(updateBookSql);
            updateBookStmt.setString(1, bookID);
            int rowsUpdated = updateBookStmt.executeUpdate();

            if (rowsUpdated == 0) {
                JOptionPane.showMessageDialog(null, "Error updating book availability. Book ID not found.", "Error", JOptionPane.ERROR_MESSAGE);
                con.rollback();
                return;
            }

            String deleteIssuedBookSql = "DELETE FROM issuedbook WHERE studentid = ? AND bookid = ?";
            PreparedStatement deleteIssuedBookStmt = con.prepareStatement(deleteIssuedBookSql);
            deleteIssuedBookStmt.setString(1, studentID);
            deleteIssuedBookStmt.setString(2, bookID);
            int rowsDeleted = deleteIssuedBookStmt.executeUpdate();

            if (rowsDeleted == 0) {
                JOptionPane.showMessageDialog(null, "Error deleting issued book record. No matching record found.", "Error", JOptionPane.ERROR_MESSAGE);
                con.rollback();
                return;
            }

            con.commit();
            JOptionPane.showMessageDialog(null, "Book returned successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);

            displayStudentIssuedBooks(); 

        } catch (SQLException ex) {
            ex.printStackTrace();
            try {
                con.rollback(); // Rollback the transaction in case of an error
            } catch (SQLException rollbackEx) {
                rollbackEx.printStackTrace();
            }
            JOptionPane.showMessageDialog(null, "An error occurred while returning the book.", "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                con.setAutoCommit(true); // Restore the default auto-commit behavior
            } catch (SQLException finalEx) {
                finalEx.printStackTrace();
            }
        }
    }                                         

