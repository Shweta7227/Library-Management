    private void displayStudentIssuedBooks() {
        String sql = "SELECT issuedbook.bookid, book.bookname, book.authorname, " +
             "issuedbook.issueddate, issuedbook.returneddate " +
             "FROM issuedbook " +  
             "JOIN book ON issuedbook.bookid = book.bookid " +  
             "WHERE issuedbook.studentid = ?";

try {
   
    PreparedStatement preparedStatement = con.prepareStatement(sql);
    preparedStatement.setString(1, stid.getText()); 
    ResultSet rs = preparedStatement.executeQuery();

    ResultSetMetaData metaData = rs.getMetaData();
    int columnCount = metaData.getColumnCount();
    Vector<String> columnNames = new Vector<>();
   
    for (int i = 1; i <= columnCount; i++) {
        columnNames.add(metaData.getColumnName(i));
    }

    Vector<Vector<Object>> data = new Vector<>();
    while (rs.next()) {
        Vector<Object> row = new Vector<>();
        for (int i = 1; i <= columnCount; i++) {
            row.add(rs.getObject(i));
        }
        data.add(row);
    }

   table.setModel(new DefaultTableModel(data, columnNames));

    rs.close();
    preparedStatement.close();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, "Error loading today's orders: " + e.getMessage());
}
    }
